export function withoutServerOwnedProfileFields<T extends Record<string, any>>(
  data: T,
): T {
  if (!data || typeof data !== "object") return data;
  const clean: Record<string, any> = { ...data };
  for (const field of SERVER_OWNED_PROFILE_FIELDS) delete clean[field];
  return clean as T;
}
